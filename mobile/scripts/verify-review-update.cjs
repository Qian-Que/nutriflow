const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
function load(name) {
  const exports = {};
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, '..', name + '.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports, require: p => load(p.replace('./', '')) });
  return exports;
}
const { reviewBody, changeReviewItem, scaleReview, removeReviewItem, needsReviewAcknowledgement } = load('recognitionDraft');
const draft = { kind: 'FOOD', confidence: 0.9, acknowledged: false, body: { clientRequestId: 'stable-id-1', note: '', calories: 200, proteinGram: 10, carbsGram: 20, fatGram: 9, fiberGram: 2, nutrients: { sodiumMg: 30 }, items: [{ name: 'Milk', estimatedWeightGram: 200, calories: 200, proteinGram: 10, carbsGram: 20, fatGram: 9, fiberGram: 2 }] } };
assert.equal(needsReviewAcknowledgement(draft), false);
assert.equal(needsReviewAcknowledgement({ ...draft, confidence: NaN }), true);
assert.throws(() => reviewBody({ ...draft, confidence: 0.69 }));
assert.throws(() => reviewBody({ ...draft, fallback: 'TEXT_ONLY' }));
assert.equal(reviewBody({ ...draft, fallback: 'TEXT_ONLY', acknowledged: true }).calories, 200);
let edited = changeReviewItem(draft, 0, 'estimatedWeightGram', '100');
assert.equal(reviewBody(edited).calories, 100);
assert.equal(edited.body.nutrients, undefined);
edited = changeReviewItem(edited, 0, 'estimatedWeightGram', '');
assert.throws(() => reviewBody(edited));
edited = changeReviewItem(edited, 0, 'estimatedWeightGram', '400');
assert.equal(reviewBody(edited).calories, 400);
assert.equal(reviewBody(edited).clientRequestId, 'stable-id-1');
assert.equal(scaleReview(draft, 0.5).body.nutrients.sodiumMg, 15);
const doubled = { ...draft, body: { ...draft.body, items: [draft.body.items[0], draft.body.items[0]] } };
assert.equal(removeReviewItem(doubled, 1).body.calories, 200);
assert.equal(removeReviewItem(draft, 0).body.items.length, 1);
for (const value of ['', '-1', 'NaN', 'Infinity', '100001']) assert.throws(() => reviewBody(changeReviewItem(draft, 0, 'calories', value)));
assert.throws(() => reviewBody(changeReviewItem(draft, 0, 'name', '')));
const exercise = { kind: 'EXERCISE', confidence: 1, acknowledged: false, body: { exerciseType: 'run', durationMin: '30', calories: '200', met: '5' } };
assert.equal(reviewBody(exercise).durationMin, 30);
for (const [key, value] of [['durationMin', 601], ['met', 21], ['calories', 5001], ['exerciseType', '']]) assert.throws(() => reviewBody({ ...exercise, body: { ...exercise.body, [key]: value } }));
const { CURRENT_VERSION, isNewerVersion, validateRelease } = load('appUpdate');
assert.equal(CURRENT_VERSION, require('../app.json').expo.version);
assert.equal(isNewerVersion('1.10.0', '1.9.9'), true);
assert.equal(isNewerVersion('1.4.0', '1.4.0'), false);
assert.equal(isNewerVersion('1.3.9', '1.4.0'), false);
assert.equal(isNewerVersion('2.0.0-rc1', '1.4.0'), false);
const release = { version: '1.5.0', url: 'https://github.com/Qian-Que/nutrition-app/releases/tag/v1.5.0', apkUrl: 'https://github.com/Qian-Que/nutrition-app/releases/download/v1.5.0/NutriFlow-v1.5.0-android.apk', size: 123 };
assert.equal(validateRelease(release).version, '1.5.0');
const canonical = JSON.parse(JSON.stringify(release).replaceAll('Qian-Que/nutrition-app', 'Qian-Que/nutriflow'));
assert.deepEqual(JSON.parse(JSON.stringify(validateRelease(release))), canonical);
assert.deepEqual(JSON.parse(JSON.stringify(validateRelease(canonical))), canonical);
assert.throws(() => validateRelease({...canonical, apkUrl:release.apkUrl}));
for (const url of ['http://github.com/Qian-Que/nutrition-app/releases/tag/v1.5.0', 'https://evil.example', 'https://github.com/other/repo']) assert.throws(() => validateRelease({ ...release, url }));
console.log('PASS: review correction, confidence gate, numeric validation, portions, stable IDs, release comparison and source allowlist');
